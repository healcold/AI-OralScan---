export function zh(value: string): string {
  if (labels[value]) return labels[value]
  return value
    .replace(/(STL face normals|OBJ normal declarations|PLY vertex normals|Source normals) are absent or not available from the parser\./g, '源文件未提供法线，或解析器无法读取。')
    .replace(/(STL face normals|OBJ normal declarations|PLY vertex normals): (\d+) checked for finite, non-zero vectors; correspondence and direction were not validated\./g, '已检查 $2 个源法线是否为有限非零向量，尚未验证对应关系与方向。')
    .replace(/(\d+) invalid source normal vectors detected; direction was not validated\./g, '检测到 $1 个无效源法线，尚未验证方向。')
    .replace(/(\d+) boundary edges, (\d+) non-manifold edges\./g, '$1 条边界边，$2 条非流形边。')
    .replace(/(\d+) exact duplicate vertex positions in the loaded representation; STL commonly repeats vertices per face\./g, '加载数据中有 $1 个完全重复的顶点位置，STL 通常按面重复顶点。')
    .replace(/(\d+) degenerate or near-degenerate faces detected\./g, '检测到 $1 个退化或近退化面。')
    .replace(/(\d+) boundary edges detected; mesh is open or non-manifold\./g, '检测到 $1 条边界边，网格开放或为非流形。')
    .replace(/(\d+) non-manifold edges detected\./g, '检测到 $1 条非流形边。')
    .replace(/(\d+) disconnected vertex-connected components detected\./g, '检测到 $1 个互不连通的顶点连通分量。')
}
